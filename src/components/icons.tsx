/**
 * 统一图标集（Lucide 风格：24×24 viewBox、2px 描边、currentColor）。
 *
 * 为什么需要它：全站曾用 emoji 当图标（🖨 📥 ⚡ 💡 🏭 📋 🔍 ✨ 等），
 * emoji 在不同系统渲染差异很大、无法跟随字色、屏幕阅读器会读出「打印机」这类
 * 无关语义，与侧栏的线性图标语言也分裂。这里用内联 SVG 取代，不引入额外依赖。
 */
import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function base({ size = 16, ...rest }: IconProps) {
  return {
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 2,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": true,
    focusable: false,
    ...rest,
  };
}

