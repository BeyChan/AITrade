import { defineConfig, devices } from "@playwright/test";
import { mkdtempSync } from "node:fs";
import os from "node:os";
import path from "node:path";

const SKIP_WEBSERVER = Boolean(process.env.E2E_SKIP_WEBSERVER);
const PORT = Number(process.env.E2E_PORT || 1699);
const BASE_URL = process.env.E2E_BASE_URL || `http://127.0.0.1:${PORT}`;
const CONFIGURED_DB_DIR = process.env.E2E_DB_DIR;
const E2E_DB_DIR = SKIP_WEBSERVER
  ? process.env.PGLITE_DATA_DIR
  : CONFIGURED_DB_DIR || mkdtempSync(path.join(os.tmpdir(), "aitrade-e2e-"));

// Keep the managed server and global teardown on the same isolated data directory.
process.env.AITRADE_E2E_DB_DIR = E2E_DB_DIR || "";
// Only a directory generated by this config may be deleted after the run.
process.env.AITRADE_E2E_MANAGED_DB = !SKIP_WEBSERVER && !CONFIGURED_DB_DIR ? "1" : "0";

export default defineConfig({
  testDir: "./e2e",
  globalTeardown: "./e2e/global-teardown.ts",
  fullyParallel: false,
  workers: 1,
  retries: process.env.CI ? 1 : 0,
  timeout: 45_000,
  expect: {
    timeout: 10_000,
  },
  reporter: [["list"]],
  use: {
    baseURL: BASE_URL,
    trace: "retain-on-failure",
    screenshot: "only-on-failure",
  },
  projects: [
    {
      name: "chromium",
      use: {
        ...devices["Desktop Chrome"],
        ...(process.env.E2E_CHANNEL ? { channel: process.env.E2E_CHANNEL as "chrome" | "msedge" } : {}),
      },
    },
  ],
  webServer: SKIP_WEBSERVER
    ? undefined
    : {
        command: `./node_modules/.bin/next start -p ${PORT}`,
        url: `${BASE_URL}/api/health`,
        env: { PGLITE_DATA_DIR: E2E_DB_DIR as string },
        reuseExistingServer: false,
        timeout: 90_000,
      },
});
